#!/usr/bin/env bash
#
#   Export goahead-test build flags for TestMe and TM_FEATURES_HEADER for C tests.
#   TM_ROUTES names route.txt with unsupported handlers and auth directives removed.
#   Run tm --rebuild after changing build flags; C test caching does not track them.
#
OUT=../build/test
HEADER="${OUT}/goahead-features.h"

set -o pipefail
FEATURES=$(goahead-test --features | tr -d '\r') || {
    echo "features.sh: cannot run goahead-test --features. Build first." >&2
    exit 1
}
mkdir -p "${OUT}" || exit 1
{
    echo "/* Generated by test/utils/features.sh from goahead-test --features. Do not edit. */"
    echo "${FEATURES}" | sed -n 's/^\(ME_[A-Z0-9_]*\)=\([0-9]*\)$/#define \1 \2/p'
} > "${HEADER}.tmp" || exit 1
mv "${HEADER}.tmp" "${HEADER}"

flag() {
    echo "${FEATURES}" | sed -n "s/^$1=//p"
}
awk -v auth="$(flag ME_GOAHEAD_AUTH)" -v cgi="$(flag ME_GOAHEAD_CGI)" -v js="$(flag ME_GOAHEAD_JAVASCRIPT)" \
        -v upload="$(flag ME_GOAHEAD_UPLOAD)" '
    $1 == "route" {
        if (auth == "0" && /[ \t](auth|abilities)=/) next
        if (cgi == "0" && /[ \t]handler=cgi([ \t\r]|$)/) next
        if (js == "0" && /[ \t]handler=jst([ \t\r]|$)/) next
        if (upload == "0" && /[ \t]handler=upload([ \t\r]|$)/) next
    }
    { print }
' route.txt > "${OUT}/route.txt" || exit 1

#   pwd -W gives MSYS a native path, which tests on Windows can pass to a native program
DIR=$(cd "${OUT}" && { pwd -W 2>/dev/null || pwd ; })
echo "${FEATURES}"
echo "TM_FEATURES_HEADER=${DIR}/goahead-features.h"
echo "TM_ROUTES=${DIR}/route.txt"
